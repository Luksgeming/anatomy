// Server component: the static art from the scene build, in two SVG layers (the front one stays for overlays).
// The scene is read on every request, so a rebuild from the edit box shows on the next refresh.
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { HomesteadConfig } from "./config";
import { HomesteadEdit } from "./HomesteadEdit";
import { HomesteadLive, type HomesteadData } from "./HomesteadLive";
import { fmtId, readoutOf } from "./model";
import "./homestead.css";

interface SceneItem { svg: string; key: number; piece: string; move: number[]; layer: "back" | "front"; kind: string; name: string; hot?: string }
interface Scene { config: HomesteadConfig; width: number; height: number; under: string; items: SceneItem[]; data: HomesteadData }

export const SCENE_FILE = join(process.cwd(), "src/figures/homestead/generated/scene.json");
const readScene = (): Scene => JSON.parse(readFileSync(SCENE_FILE, "utf8"));

// The item markup is SVG generated by our own scene build (scene/build.ts), never user input, so injecting it is safe.
function Items({ scene, layer }: { scene: Scene; layer: "back" | "front" }) {
  return (
    <g className="hs-items" data-layer={layer}>
      {scene.items
        .map((item, index) => ({ item, index }))
        .filter(({ item }) => item.layer === layer)
        .map(({ item, index }) => (
          <g
            key={item.name}
            className="it"
            data-piece={item.piece}
            data-k={item.key}
            data-m={item.move.join(",")}
            data-i={index}
            data-kind={item.kind || undefined}
            data-h={item.hot}
            dangerouslySetInnerHTML={{ __html: item.svg }}
          />
        ))}
    </g>
  );
}

// Blueprint PDF made by `npm run blueprint`, linked only when it exists.
const BLUEPRINTS = [
  { file: "blueprint-rumah-a3.pdf", label: "Blueprint A3 · tampak, denah, exploded, 360°, detail (5 lembar)" },
].filter((b) => existsSync(join(process.cwd(), "public/blueprint", b.file)));

export function HomesteadFigure({ editable = false }: { editable?: boolean }) {
  const scene = readScene();
  const { width: W, height: H, config, data } = scene;
  const s = data.stats;
  const crops = config.beds.length ? config.beds.join(", ") : "belum ada";
  const fruits = config.fruits.length ? config.fruits.join(", ") : "belum ada";
  const label = `Rumah tropis modern dua lantai di atas kavling diorama, dilihat isometrik. Lantai 1: ruang keluarga dan makan, dapur bersih, dapur kotor, kamar mandi, ruang cuci, teras depan beratap dan teras belakang ke kebun. Fasad bercat putih hangat dengan dinding batu alam di samping pintu dan panel kisi kayu di lantai 2. Lantai 2: kamar utama dan kamar 2, masing-masing dengan kamar mandi dalam, dan balkon. Atap perisai bertritisan lebar. Di luar: carport ${config.cars} mobil dan ${config.motorcycles} motor, taman depan, ${s.beds} bedengan sayur, pot herba, ${s.fruits} pohon buah, area jemur, tandon air hujan, dan zona homestead berpagar dengan kandang ${config.hens} ayam, kompos dan gudang alat.`;
  const keys = [
    { mark: "raised", label: "Atap dan lantai 2 terangkat saat rumah dibuka; fasad sisi dekat disembunyikan" },
    { mark: "flat", label: "Zona: hunian · parkir · taman hias · kebun pangan · homestead" },
  ];
  return (
    <figure className="iso-figure hs" data-color="">
      <div className="iso-plate">
        <div className="iso-plate-corners" aria-hidden="true">
          <span className="iso-plate-corner" data-corner="fig">Fig 1</span>
          <span className="iso-plate-corner" data-corner="title">{config.title}</span>
          <span className="iso-plate-corner" data-corner="hint">Arahkan ke rumah untuk membukanya</span>
          <span className="iso-plate-corner" data-corner="readout" data-readout="">{readoutOf({ night: 0 }, s)}</span>
        </div>
        <div className="hs-tip" role="tooltip" aria-hidden="true" hidden>
          <strong className="hs-tip-title" />
          <span className="hs-tip-body" />
          <em className="hs-tip-act" />
        </div>
        <div className="hs-stage" tabIndex={0} role="group" aria-label="Rumah tropis. Panah atas dan bawah membuka lantai, N mengganti siang dan malam, Esc kembali.">
          <svg className="iso-svg hs-back" viewBox={`0 0 ${W} ${H}`} role="img" aria-label={label} focusable="false">
            <g dangerouslySetInnerHTML={{ __html: scene.under }} />
            <Items scene={scene} layer="back" />
          </svg>
          <div className="hs-dusk" aria-hidden="true" />
          <svg className="iso-svg hs-front" viewBox={`0 0 ${W} ${H}`} aria-hidden="true" focusable="false">
            <Items scene={scene} layer="front" />
          </svg>
        </div>
        <HomesteadLive key={JSON.stringify(config)} data={data} />
      </div>
      <figcaption className="iso-legend">
        <span className="iso-keys">
          {keys.map((key) => (
            <span className="iso-key" key={key.label}>
              <svg className="iso-swatch" data-mark={key.mark} viewBox="0 0 16 10" aria-hidden="true" focusable="false">
                {key.mark === "lit" ? <path d="M1.5 5h13" /> : <path d={key.mark === "flat" ? "M2 6.5 8 3.5 14 6.5 8 9.5Z" : "M2 4.5 8 1.5 14 4.5 14 6 8 9 2 6Z"} />}
              </svg>
              {key.label}
            </span>
          ))}
        </span>
        <span className="iso-caption">
          Rumah 12 × 8 m dua lantai ({fmtId(s.floorM2)} m²) di kavling 20 × 25 m, dirancang untuk iklim tropis: lantai ditinggikan 40 cm,
          plafon 3,2 m, ventilasi silang lewat jendela tinggi, jendela berpeneduh, dan atap perisai 25° dengan tritisan 1,2 m. Atap
          {" "}{fmtId(s.roofM2)} m² menampung ±{fmtId(s.rainM3Year)} m³ air hujan setahun ke tandon 2.000 L; talang depan dibuang ke sumur
          resapan, dan jalan masuk berpaving rumput. Kebun pangan ({crops}) dan pohon buah ({fruits}) dekat dapur; kandang
          {" "}{s.hens} ayam (±{s.eggsPerDay} telur/hari), kompos dan gudang alat dipagari terpisah dari rumah.
        </span>
      </figcaption>
      {BLUEPRINTS.length ? (
        <nav className="hs-downloads" aria-label="Unduh blueprint">
          <span className="hs-downloads-label">Unduh PDF</span>
          {BLUEPRINTS.map((b) => (
            <a key={b.file} className="hs-button" href={`/blueprint/${b.file}`} download>
              {b.label}
            </a>
          ))}
        </nav>
      ) : null}
      {editable ? <HomesteadEdit /> : null}
    </figure>
  );
}
